/** Step 1 of the first run: one line of welcome and a single action. */
@Composable
fun OnboardingScreen(onCreateFirstButton: () -> Unit, modifier: Modifier = Modifier) {
    Surface(modifier = modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .safeDrawingPadding()
                .padding(horizontal = 32.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center,
        ) {
            Box(
                modifier = Modifier
                    .size(96.dp)
                    .clip(CircleShape)
                    .background(MaterialTheme.colorScheme.primaryContainer),
                contentAlignment = Alignment.Center,
            ) {
                Icon(
                    painter = painterResource(R.drawable.ic_mic),
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.onPrimaryContainer,
                    modifier = Modifier.size(48.dp),
                )
            }
            Spacer(Modifier.height(32.dp))
            Text(
                text = stringResource(R.string.onboarding_welcome),
                style = MaterialTheme.typography.headlineSmall,
                color = MaterialTheme.colorScheme.onBackground,
                textAlign = TextAlign.Center,
            )
            Spacer(Modifier.height(32.dp))
            Button(onClick = onCreateFirstButton, modifier = Modifier.fillMaxWidth()) {
                Text(stringResource(R.string.onboarding_create_first))
            }
        }
    }
}

@Preview(showBackground = true, backgroundColor = 0xFF121218, heightDp = 640, widthDp = 360)
@Composable
private fun OnboardingScreenPreview() {
    SoundboardTheme { OnboardingScreen(onCreateFirstButton = {}) }
}
